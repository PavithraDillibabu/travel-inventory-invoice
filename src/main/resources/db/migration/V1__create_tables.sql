CREATE TABLE transactions (
                              id VARCHAR(36) PRIMARY KEY,
                              type VARCHAR(255) NOT NULL,
                              external_id VARCHAR(255) NOT NULL,
                              currency VARCHAR(3) NOT NULL,
                              occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                              total_minor BIGINT NOT NULL,
                              metadata TEXT NOT NULL,
                              created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE transaction_taxes (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   transaction_id VARCHAR(36) NOT NULL,
                                   name VARCHAR(255) NOT NULL,
                                   rate NUMERIC(12,6),
                                   amount_minor BIGINT NOT NULL,
                                   CONSTRAINT fk_transaction_taxes_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id)
);
CREATE TABLE transaction_fees (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  transaction_id VARCHAR(36) NOT NULL,
                                  name VARCHAR(255) NOT NULL,
                                  amount_minor BIGINT NOT NULL,
                                  CONSTRAINT fk_transaction_fees_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id)
);
CREATE TABLE invoices (
                          id VARCHAR(36) PRIMARY KEY,
                          currency VARCHAR(3) NOT NULL,
                          total_minor BIGINT NOT NULL,
                          created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE invoice_lines (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               invoice_id VARCHAR(36) NOT NULL,
                               line_number INTEGER NOT NULL,
                               transaction_id VARCHAR(36) NOT NULL,
                               type VARCHAR(255) NOT NULL,
                               external_id VARCHAR(255) NOT NULL,
                               currency VARCHAR(3) NOT NULL,
                               occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                               total_minor BIGINT NOT NULL,
                               metadata TEXT NOT NULL,
                               tax_lines_snapshot TEXT NOT NULL,
                               fee_lines_snapshot TEXT NOT NULL,
                               CONSTRAINT fk_invoice_lines_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id)
);
CREATE TABLE invoice_taxes (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               invoice_id VARCHAR(36) NOT NULL,
                               name VARCHAR(255) NOT NULL,
                               rate NUMERIC(12,6),
                               amount_minor BIGINT NOT NULL,
                               CONSTRAINT fk_invoice_taxes_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id)
);
CREATE TABLE invoice_fees (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              invoice_id VARCHAR(36) NOT NULL,
                              name VARCHAR(255) NOT NULL,
                              amount_minor BIGINT NOT NULL,
                              CONSTRAINT fk_invoice_fees_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id)
);
